#include <stdio.h>

int main(void)
{
    int a = 3;

    /*
       截图中的原始写法：
           a += a -= a * a;
       在 C 语言中，这种写法涉及对 a 的未排序读写/多次修改，
       存在未定义行为风险，不应依赖其输出或当作规范用法。

       如果想表达“先做减法赋值，再做加法赋值”，请拆开：
    */
    a -= a * a;      // 3 - 9 = -6
    a += a;          // -6 + (-6) = -12

    printf("%d\n", a);
    return 0;
}
